        // Scroll effect untuk navbar
        $(window).scroll(function() {
            if ($(this).scrollTop() > 800) { // Ganti 500 dengan tinggi header
                $('#navbar').addClass('scrolled');
            } else {
                $('#navbar').removeClass('scrolled');
            }
        });

